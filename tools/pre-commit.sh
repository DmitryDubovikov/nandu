#!/bin/sh
# Тормоз для правила 14 CLAUDE.md: заголовок шага не выдумывает потребность задним числом.
#
# Хук смотрит только ДОБАВЛЕННЫЕ строки в staged .md и ругается на заголовки вида
# «**Шаг N — нужн…**» / «**Шаг N — нужен…**». Такой заголовок законен, когда величина названа
# в блоке «✅ План готов» шага 1, спрошена в условии или поставлена целью в предыдущем шаге, —
# проверить это может только человек. Поэтому не запрет, а остановка:
#
#     NANDU_STEP_OK=1 git commit …     — цель действительно названа в плане, коммить
#
# Установка:  ln -sf ../../tools/pre-commit.sh .git/hooks/pre-commit

[ -n "$NANDU_STEP_OK" ] && exit 0

# CLAUDE.md исключён: правило 14 само цитирует дефектные заголовки как примеры
hits=$(git diff --cached -U0 --diff-filter=ACM -- '*.md' ':(exclude)CLAUDE.md' \
       | grep '^+' | grep -v '^+++' \
       | grep -n 'Шаг [0-9] — нуж')

[ -z "$hits" ] && exit 0

cat >&2 <<MSG
⚠ Правило 14 CLAUDE.md — цель шага не выдумывается задним числом.

Новые заголовки:
$hits

Заголовок законен, только если величина уже названа:
  • в блоке «✅ План готов: Ответ = …» шага 1,
  • в самом условии задачи,
  • или как цель предыдущего шага.
Иначе порядок диктует структура записи, и заголовок должен называть наблюдение:
  «Шаг 5 — нужны a и c по отдельности» → «Шаг 5 — в третьем контуре стоит a, но не стоит c».

Проверил, цель названа в плане:  NANDU_STEP_OK=1 git commit …
MSG
exit 1

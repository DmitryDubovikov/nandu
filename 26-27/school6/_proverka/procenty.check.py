"""Проверка пары 2 «Проценты и пропорции»: числа примеров учебника и ответы решебника.
Точная арифметика (Fraction); где есть смысл — перебор. Запуск: python3 procenty.check.py
"""
from fractions import Fraction as F
from itertools import permutations

n = 0


def ok(cond, label):
    global n
    n += 1
    assert cond, "НЕ СХОДИТСЯ: " + label


def pct(p):
    return F(p) / 100


# ---------- УЧЕБНИК ----------
# вводный раздел
ok(400 * pct(15) == 60, "15% от 400")
ok(60 / pct(15) == 400, "60 : 0,15")
ok(F(60, 400) * 100 == 15, "60 из 400")
ok(F(1, 2) == pct(50) and F(1, 4) == pct(25) and F(1, 5) == pct(20) and F(1, 10) == pct(10), "таблица долей")
# ритуалы
ok(300 * pct(20) == 60 and 50 * pct(20) == 10, "ритуал 1")
ok(400 * pct(18) == 72 and F(400, 5) == 80, "ритуал 3")
ok(F(3, 2) == F(15, 10), "ритуал 5")
# глава 1
ok(pct(37) == F(37, 100) and pct(5) == F(5, 100) and pct(250) == F(5, 2) and pct(F(4, 10)) == F(4, 1000), "гл.1 в дробь")
ok(pct(12) == F(3, 25) and pct(40) == F(2, 5), "гл.1 сокращение")
ok(F(63, 100) * 100 == 63 and F(8, 100) * 100 == 8 and F(17, 10) * 100 == 170 and F(3, 4) * 100 == 75, "гл.1 в проценты")
ok(F(7, 25) * 100 == 28 and F(1, 8) * 100 == F(25, 2), "гл.1 7/25, 1/8")
ok(F(700, 25) == 28 and F(25, 4) < 7, "гл.1 разбор и прикидка")
# глава 2
ok(F(250 - 200, 200) == pct(25), "гл.2 было 200 стало 250")
ok(18 / pct(24) == 75 and F(1800, 24) == 75 and 18 * 4 == 72, "гл.2 разбор А")
ok(920 - 800 == 120 and F(120, 800) == pct(15), "гл.2 разбор Б")
ok(round(float(F(120, 920) * 100)) == 13, "гл.2 ошибка ≈13%")
# глава 3
ok(10000 * pct(6) == 600 and [10000 + k * 600 for k in (1, 2, 3)] == [10600, 11200, 11800], "гл.3 таблица")
ok(20000 * pct(8) == 1600 and 20000 + 3 * 1600 == 24800, "гл.3 разбор А")
ok(15000 - 12000 == 3000 and 12000 * pct(5) == 600 and 3000 // 600 == 5, "гл.3 разбор Б")
ok(20000 + 1600 == 21600 and 21600 * pct(8) == 1728, "гл.3 ошибка: 8% от 21 600")
# глава 4
s = 10000
rows = []
for _ in range(3):
    add = s * pct(10)
    rows.append((s, add, s + add))
    s += add
ok(rows == [(10000, 1000, 11000), (11000, 1100, 12100), (12100, 1210, 13310)], "гл.4 таблица по годам")
ok(all(F(b, a) == F(11, 10) for a, _, b in rows), "гл.4 частные 1,1")
ok(10000 * F(11, 10) ** 3 == 13310, "гл.4 одно произведение")
ok(1000 * F(8, 10) == 800 and 1000 - 200 == 800, "гл.4 −20% = ×0,8")
ok(20000 * F(11, 10) ** 3 == 26620 and 20000 + 3 * 2000 == 26000, "гл.4 разбор А")
ok(1000 * F(12, 10) == 1200 and 1200 * F(8, 10) == 960 and F(40, 1000) == pct(4), "гл.4 разбор Б")
lst = [(1 + pct(p)) * (1 - pct(p)) for p in (10, 20, 30, 50)]
ok(lst == [F(99, 100), F(96, 100), F(91, 100), F(75, 100)], "гл.4 список +p/−p")
ok(all((1 + pct(p)) * (1 - pct(p)) < 1 for p in range(1, 100)), "гл.4 +p/−p всегда меньше 1 (перебор)")
ok(F(15, 10) * F(8, 10) == F(12, 10) and 2 * F(1, 2) == 1, "гл.4 разные проценты")
# глава 5
ok(F(12, 4) == 3 and 12 - 4 == 8 and F(40, 24) == F(5, 3), "гл.5 отношение")
ok(F(4000, 800) == 5, "гл.5 кг и г")
for part, b, g in [(1, 3, 2), (2, 6, 4), (4, 12, 8), (6, 18, 12), (10, 30, 20)]:
    ok(b == 3 * part and g == 2 * part and F(b, g) == F(3, 2) and b + g == 5 * part, "гл.5 таблица частей")
ok(30 // 5 == 6, "гл.5 класс 30")
ok(240 // 3 == 80 and 5 * 80 == 400 and 8 * 80 == 640 and 400 + 240 == 640, "гл.5 разбор")
ok(abs(float(F(5, 3)) - 1.7) < 0.05, "гл.5 ≈1,7")
# глава 6
ok(1000 == 10 * 100, "гл.6 1 см = 10 м")
ok(3 * 1000 == 3000 and 3000 == 30 * 100 and 3000 // 1000 == 3 and 3000 // 3 == 1000, "гл.6 таблица на числах")
ok(100000 == 1 * 100000 and 10000000 == 100 * 100000, "гл.6 мелкие масштабы")
ok(6 * 25000 == 150000 and F(150000, 100000) == F(3, 2), "гл.6 разбор А")
ok(24 * 100 == 2400 and 2400 // 3 == 800, "гл.6 разбор Б")
ok(F(3, 24) == F(1, 8) and 24 // 8 == 3, "гл.6 ошибка")
# глава 7
ok(F(3, 4) == F(9, 12) == F(75, 100), "гл.7 3:4 = 9:12")
for c, d in [(6, 8), (9, 12), (12, 16)]:
    ok(F(3, 4) == F(c, d) and 3 * d == 4 * c, "гл.7 список пропорций")
ok([3 * 8, 3 * 12, 3 * 16] == [24, 36, 48], "гл.7 произведения списка")
ok(3 * 13 == 39 and 4 * 9 == 36 and F(3, 4) != F(9, 13), "гл.7 неверная 3:4 и 9:13")
ok(4 * 15 == 60 == 6 * 10, "гл.7 разбор А")
ok(8 * 21 == 168 and 168 // 12 == 14 and F(8, 14) == F(12, 21) == F(4, 7), "гл.7 разбор Б")
ok(3 * 9 == 27 and 4 * 12 == 48, "гл.7 ошибка")
# глава 8
for a, b, c, d in [(4, 10, 6, 15), (4, 6, 10, 15), (15, 10, 6, 4), (10, 4, 15, 6)]:
    ok(F(a, b) == F(c, d) and a * d == b * c == 60, "гл.8 таблица")
ok(4 * 10 == 40 and 15 * 6 == 90 and F(4, 15) != F(6, 10), "гл.8 перестановка, разлучающая пару")
ok(2 * 18 == 4 * 9 == 36 and F(2, 4) == F(9, 18) == F(1, 2), "гл.8 обратный ход")
# 7x = 5y -> x : y = 5 : 7 (перебор)
ok(all(F(x, y) == F(5, 7) for x in range(1, 200) for y in range(1, 200) if 7 * x == 5 * y), "гл.8 разбор")
ok(7 * 5 == 5 * 7 == 35 and 7 * 7 == 49 and 5 * 5 == 25, "гл.8 проверка и ошибка")
# глава 9
ok([F(90, 2), F(135, 3), F(225, 5)] == [45, 45, 45], "гл.9 цена")
ok(45 * 4 == 180 and 720 // 45 == 16 and 720 % 45 == 0, "гл.9 разбор")
ok(88 + 2 == 90 and 88 + 3 == 91 != 135, "гл.9 ошибка")
# глава 10
xs = [1, 2, 3, 4, 5]
ok([5 * x for x in xs] == [5, 10, 15, 20, 25], "гл.10 прямая, список")
xs2 = [1, 2, 3, 4, 5, 6]
ok([F(60, x) for x in xs2] == [60, 30, 20, 15, 12, 10], "гл.10 обратная, список")
ok([F(16, 4), F(15, 5), F(10, 10)] == [4, 3, 1] and [4 * 16, 5 * 15, 10 * 10] == [64, 75, 100], "гл.10 бидон")
ok(2 * 60 == 3 * 40 == 5 * 24 == 120 and 120 // 8 == 15, "гл.10 разбор")
ok(F(10, 2) == 5 and abs(float(F(20, 3)) - 6.7) < 0.05 and F(100, 5) == 20, "гл.10 ошибка")
# глава 11
ok(F(10 * 90, 6) == 150 and F(90, 6) == F(150, 10) == 15, "гл.11 тетради")
ok(4 * 15 == 60 and F(60, 6) == 10, "гл.11 рабочие")
ok(F(90, 6) == F(150, 10) and F(90, 150) == F(6, 10), "гл.11 вывод прямой: 90 : 6 = x : 10 -> 90 : x = 6 : 10")
ok(4 * 15 == 6 * 10 and F(4, 6) == F(10, 15), "гл.11 вывод обратной: 4 × 15 = 6 × x -> 4 : 6 = x : 15")
ok(14 * 1200 == 16800 and 16800 // 8 == 2100 and 1200 // 8 == 150 and 150 * 14 == 2100, "гл.11 разбор А")
ok(5 * 12 == 60 and 60 // 4 == 15, "гл.11 разбор Б")
ok(F(4 * 12, 5) == F(96, 10), "гл.11 ошибка 9,6")
# глава 12
ok(96 // 8 == 12 and (3 * 12, 5 * 12) == (36, 60) and 36 + 60 == 96, "гл.12 разбор А")
ok(F(120, 150) == F(4, 5), "гл.12 рост")
ok(168 // 12 == 14 and [2 * 14, 3 * 14, 7 * 14] == [28, 42, 98] and 28 + 42 + 98 == 168, "гл.12 разбор Б")
ok(96 // 2 == 48 and 3 * 48 == 144 and 5 * 48 == 240 and 144 + 240 == 384, "гл.12 ошибка на числах")

# ---------- РЕШЕБНИК ----------
ok((pct(7), pct(60), pct(125)) == (F(7, 100), F(3, 5), F(5, 4)), "1.1")
ok((F(9, 100) * 100, F(7, 20) * 100, F(18, 10) * 100) == (9, 35, 180), "1.2")
ok(F(14, 40) * 100 == 35 and F(26, 40) * 100 == 65 == 100 - 35, "1.3")
ok(350 * pct(24) == 84, "2.1")
ok(54 / pct(12) == 450, "2.2")
ok(F(2500 - 2200, 2500) == pct(12), "2.3")
ok(15000 * pct(6) == 900 and 15000 + 4 * 900 == 18600, "3.1")
ok(8000 * pct(7) == 560 and 11360 - 8000 == 3360 and F(3360, 560) == 6, "3.2")
m = [400 + k * 400 * pct(15) for k in range(5)]
ok(m == [400, 460, 520, 580, 640] and sum(m) == 2600, "3.3")
ok(4000 * F(13, 10) ** 2 == 6760, "4.1")
ok(F(125, 100) * F(8, 10) == 1, "4.2")
ok(20000 * F(105, 100) ** 2 == 22050 and F(22050 - 20000, 20000) == pct(F(1025, 100)), "4.3")
ok(F(45, 15) == 3 and F(2000, 250) == 8, "5.1")
ok([(a, b) for a in range(1, 500) for b in range(1, 500) if 8 * a == 5 * b and b - a == 21] == [(35, 56)] and 21 // 3 == 7, "5.2 (перебор)")
ok(21 // 7 == 3 and 3 * 3 == 9 and 21 + 9 == 30 and 21 - 9 == 12, "5.3")
ok(7 * 200 == 1400 and 1400 // 100 == 14, "6.1")
ok(6 * 100000 // 4 == 150000, "6.2")
ok(8 * 500 // 100 == 40 and 5 * 500 // 100 == 25 and 40 * 25 == 1000, "6.3")
ok(F(9 * 20, 12) == 15, "7.1")
ok(F(24, 10) * F(15, 10) == F(36, 10) and F(36, 10) / F(6, 10) == 6 and F(24, 10) / 6 == F(6, 10) / F(15, 10), "7.2")
ok(6 * 35 == 14 * 15 == 210 and 2 * 21 == 6 * 7 == 42, "7.3")
props = {p for p in permutations((2, 6, 7, 21)) if F(p[0], p[1]) == F(p[2], p[3])}
ok((2, 6, 7, 21) in props and len(props) == 8, "7.3 перебор: верных расстановок 8")
for a, b, c, d in [(6, 8, 15, 20), (15, 6, 20, 8), (20, 15, 8, 6)]:
    ok(F(a, b) == F(c, d) and a * d == b * c == 120, "8.1")
ok(all(F(a, b) == F(8, 3) for a in range(1, 200) for b in range(1, 200) if 3 * a == 8 * b), "8.2")
ok(4 * 70 == 280 and 280 // 7 == 40 and F(70, 40) == F(7, 4) and all(F(p, v) == F(7, 4) for p in range(1, 300) for v in range(1, 300) if 4 * p == 7 * v), "8.3 (перебор)")
ok([F(210, 3), F(350, 5), F(560, 8)] == [70] * 3 and 70 * 12 == 840, "9.1")
ok([4 * a for a in (3, 5, 10)] == [12, 20, 40] and [a * a for a in (3, 5, 10)] == [9, 25, 100], "9.2")
ok(195 // 3 == 65 and 65 * 7 == 455 and 780 // 65 == 12 and 780 % 65 == 0, "9.3")
ok([F(18, 2), F(27, 3), F(45, 5)] == [9] * 3 and 2 * 18 == 3 * 12 == 6 * 6 == 36, "10.1")
ok(9 * 16 == 144 and 144 // 6 == 24 and 144 // 8 == 18 and 144 % 6 == 0 and 144 % 8 == 0, "10.3")
ok(385 // 7 == 55 and 55 * 12 == 660 and F(12 * 385, 7) == 660, "11.1")
ok(8 * 9 == 72 and 72 // 6 == 12, "11.2")
ok(7 * 660 == 12 * 385 == 4620 and 6 * 12 == 72 and 12 * 20 == 240 and 20000 * F(105, 100) == 21000, "ответы 11.x и 4.3: добавленные звенья")
ok(8 * 30 == 240 and 240 // 12 == 20 and 30 - 20 == 10, "11.3")
ok(120 // 10 == 12 and (36, 84) == (3 * 12, 7 * 12), "12.1")
ok(180 // 15 == 12 and [24, 60, 96] == [2 * 12, 5 * 12, 8 * 12] and 24 + 60 + 96 == 180, "12.2")
ok(84 // 21 == 4 and [20, 24, 40] == [5 * 4, 6 * 4, 10 * 4] and 84 // 3 == 28 and 28 - 20 == 8, "12.3")

print(f"OK: {n} проверок прошли")

"""Проверка пары 5 «Дроби, движение, среднее» (school6): примеры учебника, ответы решебника,
числа достроенных таблиц и предложенные замены задач. Точная арифметика: fractions.Fraction."""
from fractions import Fraction as F

ok = 0


def eq(name, got, want):
    global ok
    assert got == want, f"{name}: {got} != {want}"
    ok += 1


def terminates(fr):
    d = F(fr).denominator
    for p in (2, 5):
        while d % p == 0:
            d //= p
    return d == 1


D = lambda s: F(s.replace(",", "."))

# ---------- Учебник: ритуалы ----------
eq("R1", D("0,25") * F(2, 5), D("0,25") * 2 / 5)
eq("R2 1/8", F(1, 8), D("0,125"))
eq("R2 7/20", F(7, 20), D("0,35"))
eq("R2 9/24", F(9, 24), D("0,375"))
# таблица ритуала 2: 1/2 … 1/10, перебором: делится ли 10, 100, 1000 (и дальше) на знаменатель
table = {2: (5, 10), 4: (25, 100), 5: (2, 10), 8: (125, 1000), 10: (1, 10)}
for n in range(2, 11):
    brute = any(10 ** k % n == 0 for k in range(1, 40))
    eq(f"R2 terminates 1/{n}", brute, terminates(F(1, n)))
    eq(f"R2 table 1/{n}", brute, n in table)
    if n in table:
        num, den = table[n]
        eq(f"R2 value 1/{n}", F(num, den), F(1, n))
        eq(f"R2 mult 1/{n}", n * num, den)
eq("R2 0,35", F(35, 100), F(7, 20))
for fr in (F(1, 3), F(1, 6), F(2, 7), F(5, 9)):
    eq(f"не переводится {fr}", terminates(fr), False)
for fr in (F(1, 2), F(1, 4), F(1, 5), F(1, 8), F(1, 20), F(1, 25), F(6, 15)):
    eq(f"переводится {fr}", terminates(fr), True)
# ритуал 4
eq("R4", D("0,25") * D("0,4"), D("0,1"))

# ---------- Глава 1 ----------
naiz = {(1, 2): "0,5", (1, 4): "0,25", (3, 4): "0,75", (1, 5): "0,2", (2, 5): "0,4", (3, 5): "0,6",
        (4, 5): "0,8", (1, 8): "0,125", (3, 8): "0,375", (1, 20): "0,05"}
for (a, b), s in naiz.items():
    eq(f"наизусть {a}/{b}", F(a, b), D(s))
# пример А
eq("1A произведение", D("0,25") * F(2, 5), F(1, 10))
eq("1A сокращение", F(1, 4) * F(2, 5), F(1, 2) * F(1, 5))
eq("1A ответ", F(1, 3) + D("0,25") * F(2, 5), F(13, 30))
eq("1A сборка", F(10, 30) + F(3, 30), F(13, 30))
# пример Б
eq("1Б скобка", D("2,5") - (1 + F(1, 4)), D("1,25"))
eq("1Б частное", D("1,25") / D("0,5"), D("2,5"))
eq("1Б ответ", (D("2,5") - (1 + F(1, 4))) / D("0,5") + D("0,3"), D("2,8"))
eq("1Б вторая дорога скобка", F(5, 2) - F(5, 4), F(5, 4))
eq("1Б вторая дорога", F(5, 4) * 2 + F(3, 10), F(28, 10))
# ошибки
eq("1 ош1", D("0,33") + D("0,1"), D("0,43"))
eq("1 ош2", (F(1, 3) + F(1, 4)) * F(2, 5), F(7, 30))
eq("1 ош2 промежуточное", F(1, 3) + F(1, 4), F(7, 12))

# ---------- Глава 2 ----------
own = 8
rows = {0: (8, 8, 16, 0), 1: (9, 7, 16, 2), 2: (10, 6, 16, 4), 3: (11, 5, 16, 6)}
for cur, (down, up, s, d) in rows.items():
    eq(f"2 табл {cur}", (own + cur, own - cur, own + cur + own - cur, (own + cur) - (own - cur)), (down, up, s, d))
    eq(f"2 табл полусумма {cur}", F(down + up, 2), own)
    eq(f"2 табл полуразность {cur}", F(down - up, 2), cur)
# пример А
eq("2A расстояние", (8 + 2) * 3, 30)
eq("2A ответ", F(30, 8 - 2), 5)
# пример Б
eq("2Б собственная", F(24 + 16, 2), 20)
eq("2Б течение", F(24 - 16, 2), 4)
eq("2Б плот", 4 * D("2,5"), 10)
eq("2 ош2", (10 * 3, 8 * 3), (30, 24))

# ---------- Глава 3 ----------
petya = [5, 4, 4, 3, 4]
eq("3 Петя", (sum(petya), F(sum(petya), len(petya))), (20, 4))
eq("3 границы", min(petya) <= F(sum(petya), 5) <= max(petya), True)
eq("3 max", 5 * 5, 25)
eq("3 min", 3 * 5, 15)
# пример А
eq("3A сумма 4", D("4,25") * 4, 17)
eq("3A сумма 5", D("4,4") * 5, 22)
eq("3A ответ", D("4,4") * 5 - D("4,25") * 4, 5)
# таблица «часы на 12 и на 18»
tab = {(1, 1): (30, 2, "15"), (2, 1): (42, 3, "14"), (3, 1): (54, 4, "13,5")}
for (h12, h18), (path, t, v) in tab.items():
    eq(f"3 табл {h12},{h18}", (12 * h12 + 18 * h18, h12 + h18, F(12 * h12 + 18 * h18, h12 + h18)), (path, t, D(v)))
# пример Б
eq("3Б", F(36 + 36, F(36, 12) + F(36, 18)), D("14,4"))
eq("3Б времена", (F(36, 12), F(36, 18)), (3, 2))
eq("3Б замена", D("14,4") * 5, 72)
eq("3Б среднее скоростей", F(12 + 18, 2), 15)
# ошибка 2
eq("3 ош2", F(4 * 20 + D("3,5") * 30, 50), D("3,7"))
eq("3 ош2 суммы", (4 * 20, D("3,5") * 30), (80, 105))
eq("3 ош2 неверно", F(4 + D("3,5"), 2), D("3,75"))
# ошибка 3 (достроенные числа)
week = [70, 0, 50, 0, 0, 90, 0]
eq("3 ош3", (sum(week), F(sum(week), 7), F(sum(week), 3)), (210, 30, 70))

# ---------- Решебник ----------
eq("1.1", D("0,8") * F(5, 6) - F(1, 4), F(5, 12))
eq("1.1 шаг", F(4, 5) * F(5, 6), F(2, 3))
eq("1.2", (2 + F(1, 4) - D("0,75")) / F(6, 15) + D("0,5"), D("4,25"))
eq("1.2 шаги", (D("2,25") - D("0,75"), D("1,5") / D("0,4")), (D("1,5"), D("3,75")))
otl = 1 + F(2, 3) + D("0,7")
eq("1.3 отлили", otl, 2 + F(11, 30))
eq("1.3 осталось", D("5,2") - otl, 2 + F(5, 6))
eq("1.3 шаги", (F(20, 30) + F(21, 30), 5 + F(6, 30) - 2 - F(11, 30)), (F(41, 30), 2 + F(25, 30)))
eq("1.3 не переводится", terminates(F(2, 3)), False)
eq("2.1", (D("14,5") + D("2,5"), D("14,5") - D("2,5"), 51 / (D("14,5") - D("2,5"))), (17, 12, D("4,25")))
eq("2.2", (F(21 + 15, 2), F(21 - 15, 2), 21 * 3, 15 * 3, 21 * 3 - 15 * 3), (18, 3, 63, 45, 18))
vd, vu = F(120, 4), F(120, 6)
eq("2.3", (vd, vu, (vd + vu) / 2, (vd - vu) / 2, 120 / ((vd + vu) / 2), vd - vu), (30, 20, 25, 5, D("4,8"), 10))
nums = [D(s) for s in ("3,6", "4,2", "5", "2,8", "4,9")]
eq("3.1", (sum(nums), sum(nums) / 5), (D("20,5"), D("4,1")))
eq("3.2", (150 * 12, 175 * 8, 12 * 150 + 8 * 175, F(12 * 150 + 8 * 175, 20), F(150 + 175, 2)), (1800, 1400, 3200, 160, D("162,5")))
eq("3.3", (3 * 4 + 1 * 40, F(3 * 4 + 40, 4), F(4 + 40, 2)), (52, 13, 22))

print(f"OK: {ok} проверок прошли")

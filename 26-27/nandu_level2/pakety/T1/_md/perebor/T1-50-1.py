# T1-50-1 — спортивный магазин.
# Перебор всех наборов (b мячей, r ракеток, j скакалок), каждое число от 0 до 200,
# и проверка трёх данных: всего 40 предметов; со скидкой 25 % на мячи заказ стоит $1320;
# со скидкой 50 % на ракетки заказ стоит $1290.
# Цены: мяч $120 (со скидкой $90), ракетка $40 (со скидкой $20), скакалка $10.

LIMIT = 200
found = []
for b in range(LIMIT + 1):
    for r in range(LIMIT + 1):
        for j in range(LIMIT + 1):
            if b + r + j != 40:
                continue
            if b * 120 * 75 // 100 + r * 40 + j * 10 != 1320:
                continue
            if b * 120 + r * 40 * 50 // 100 + j * 10 != 1290:
                continue
            found.append((b, r, j))

print("перебрано наборов:", (LIMIT + 1) ** 3)
print("подходят (мячи, ракетки, скакалки):", found)
